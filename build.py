#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Build the 此刻便是春天 workbench from data-driven sources.

Current scope:
  - Read global config from data/workbench.json (theme + module registry).
  - Load enabled module JSON files from data/modules/.
  - Enrich the reading module via transformers/reading.py.
  - Replace theme tokens in module metadata.
  - Compile styles/main.scss into CSS and inject it into the HTML template.
  - Render the workbench HTML from templates/workbench.html.
  - Backup the old workbench and validate the result.

Cleanup rules:
  1. Pre-build cleanup: remove leftover temporary artifacts and old backups.
  2. Post-build cleanup: runs after full validation to remove newly generated
     temporary artifacts such as __pycache__ and .trae-html-share-packages.
  Note: __pycache__ and .trae-html-share-packages are regenerated by Python
  and Trae during execution; they are cleaned on every build.

Usage:
    python build.py
    python build.py --skip-validate
    python build.py --dry-run
"""


def load_workbench_config() -> dict:
    """Load the global workbench configuration."""
    config_path = DATA_DIR / 'workbench.json'
    if not config_path.exists():
        raise FileNotFoundError(f'Workbench config not found: {config_path}')
    return json.loads(config_path.read_text(encoding='utf-8'))


def get_active_tokens(config: dict) -> dict:
    """Return the merged token map for the active theme.

    SASS variables in styles/_variables.scss are the single source of truth for
    the default (light) theme. workbench.json themes only declare overrides for
    alternate themes (e.g. dark). This function merges base tokens with the
    active theme's overrides so module data always receives complete color
    values.
    """
    active = config.get('activeTheme', 'light')
    themes = config.get('themes', {})
    if active not in themes:
        raise ValueError(f'Active theme not found: {active}')

    base_tokens = _load_base_tokens_from_scss()
    overrides = themes[active].get('tokens', {})
    merged = {**base_tokens, **overrides}
    return merged


def load_modules(config: dict) -> list[dict]:
    """Load all enabled module data files."""
    modules = []
    for reg in config.get('modules', []):
        if not reg.get('enabled', True):
            print(f'  [skip] disabled module: {reg.get("id")}')
            continue

        module_file = MODULES_DIR / reg['file']
        if not module_file.exists():
            print(f'  [warn] module file not found: {module_file}')
            continue

        data = json.loads(module_file.read_text(encoding='utf-8'))
        data['_registry'] = reg
        modules.append(data)
    return modules


def apply_tokens(obj, tokens: dict):
    """Recursively replace token names with actual color values."""
    if isinstance(obj, dict):
        return {k: apply_tokens(v, tokens) for k, v in obj.items()}
    if isinstance(obj, list):
        return [apply_tokens(v, tokens) for v in obj]
    if isinstance(obj, str) and obj in tokens:
        return tokens[obj]
    return obj


def enrich_module(data: dict) -> dict:
    """Run a module-specific transformer if one exists."""
    module_id = data.get('id')
    transformer_path = TRANSFORMERS_DIR / f'{module_id}.py'
    if not transformer_path.exists():
        return data

    try:
        module = importlib.import_module(module_id)
        enrich = getattr(module, 'enrich_module', None)
        if enrich:
            return enrich(data)
    except Exception as exc:
        print(f'  [warn] transformer failed for {module_id}: {exc}')

    return data


def backup_workbench() -> Path:
    """Create a timestamped backup next to the workbench."""
    suffix = f'.html.bak-{datetime.now():%Y%m%d_%H%M%S}'
    backup = WORKBENCH.with_suffix(suffix)
    backup.write_text(WORKBENCH.read_text(encoding='utf-8'), encoding='utf-8')
    return backup


def _build_theme_script(config: dict) -> str:
    """Build the inline JS that applies and toggles themes.

    Base tokens are loaded from styles/_variables.scss and merged with each
    theme's overrides so that workbench.json only needs to declare differences
    for alternate themes.
    """
    themes = config.get('themes', {})
    default_theme = config.get('activeTheme', 'light')
    base_tokens = _load_base_tokens_from_scss()

    merged_themes = {}
    for name, theme in themes.items():
        merged_themes[name] = {
            **theme,
            'tokens': {**base_tokens, **theme.get('tokens', {})},
        }

    themes_js = json.dumps(merged_themes, ensure_ascii=False)
    return f'''<script>
(function() {{
  const WORKBENCH_THEMES = {themes_js};
  const DEFAULT_THEME = '{default_theme}';

  function applyWorkbenchTheme(name) {{
    const theme = WORKBENCH_THEMES[name] || WORKBENCH_THEMES[DEFAULT_THEME];
    const root = document.documentElement;
    Object.entries(theme.tokens).forEach(function(entry) {{
      root.style.setProperty('--' + entry[0], entry[1]);
    }});
    try {{ localStorage.setItem('workbench-theme', name); }} catch (e) {{}}
    const btn = document.getElementById('theme-toggle');
    if (btn) btn.textContent = (name === 'dark') ? '☀️' : '🌙';
  }}

  function toggleWorkbenchTheme() {{
    const current = localStorage.getItem('workbench-theme') || DEFAULT_THEME;
    applyWorkbenchTheme(current === 'dark' ? 'light' : 'dark');
  }}

  const saved = localStorage.getItem('workbench-theme') || DEFAULT_THEME;
  applyWorkbenchTheme(saved);

  window.toggleWorkbenchTheme = toggleWorkbenchTheme;
  window.applyWorkbenchTheme = applyWorkbenchTheme;
}})();
</script>'''


def _compile_styles() -> str:
    """Compile styles/main.scss into CSS for inline injection."""
    if not MAIN_SCSS.exists():
        raise FileNotFoundError(f'SCSS entry not found: {MAIN_SCSS}')
    return sass.compile(filename=str(MAIN_SCSS), output_style='compressed')


def _extract_year(name: str) -> int | None:
    m = re.search(r'(\d{4})年', name)
    return int(m.group(1)) if m else None


def _build_reading_workspace(data: dict) -> tuple[str, str]:
    """Build (constants_js, workspace_js) for the reading module."""
    constants = []
    items = []

    for category in data.get('categories', []):
        cat_name = category.get('name', '')
        cat_icon = category.get('icon', '')
        cat_icon_bg = category.get('iconBg', '')
        cat_items = []

        for item in category.get('items', []):
            year = _extract_year(item['name'])
            if year is None:
                raise ValueError(f'Cannot extract year from reading item: {item["name"]}')

            constants.append(f'    const readingHtml{year} = `{item["readingHtml"]}`;')

            cat_items.append(
                f'''              {{
                code: '{item.get("code", "")}', name: '{item["name"]}', credits: {item.get("credits", 0)},
                type: '{item["type"]}', exam: '{item.get("exam", "")}', stage: '{item.get("stage", "")}', chapters: {item["chapters"]}, done: {item.get("done", 0)},
                current: '{item.get("current", "")}', tasks: {json.dumps(item.get("tasks", []), ensure_ascii=False)}, review: '{item.get("review", "")}',
                readingHtml: readingHtml{year}
              }}'''
            )

        items_joined = ',\n'.join(cat_items)
        items.append(
            f'''          {{
            name: '{cat_name}', icon: '{cat_icon}', iconBg: '{cat_icon_bg}',
            items: [
{items_joined}
            ]
          }}'''
        )

    categories_joined = ',\n'.join(items)
    workspace_js = f'''      {{
        id: '{data["id"]}', name: '{data["name"]}', icon: '{data.get("icon", "")}', iconBg: '{data.get("iconBg", "")}',
        categories: [
{categories_joined}
        ]
      }}'''

    constants_joined = '\n\n'.join(constants)
    return constants_joined + '\n', workspace_js


def run_validate() -> None:
    """Run the workbench validation script."""
    validate_script = SKILLS_DIR / 'validate_workbench.py'
    result = subprocess.run(
        [sys.executable, str(validate_script)],
        capture_output=True,
        text=True,
    )
    print(result.stdout)
    if result.returncode != 0:
        print(result.stderr, file=sys.stderr)
        raise SystemExit(result.returncode)


def _is_protected(path: Path) -> bool:
    """Return True if path is a protected root path or a protected subdirectory.

    Protected paths guard core files and directories against wholesale
    deletion. Directories inside a protected root are also protected so that
    a buggy cleanup pattern cannot wipe out core subdirectories such as
    .trae/skills or Workbench/data. Known temporary directories matching
    temp_dir_patterns are still allowed to be cleaned.
    """
    resolved = path.resolve()
    protected_paths = CLEANUP_CONFIG['protected_paths']
    temp_patterns = CLEANUP_CONFIG['temp_dir_patterns']

    for protected in protected_paths:
        try:
            protected_resolved = protected.resolve()
        except OSError:
            continue

        # Exact match: the protected root itself.
        if resolved == protected_resolved:
            return True

        # Directory inside a protected root.
        if path.is_dir():
            try:
                relative = resolved.relative_to(protected_resolved)
            except ValueError:
                continue
            if relative.parts and not any(
                any(part.startswith(pat.rstrip('*')) or part == pat for pat in temp_patterns)
                for part in relative.parts
            ):
                return True

    return False


def _remove_path(path: Path) -> None:
    """Remove a file or directory tree, refusing protected paths."""
    if _is_protected(path):
        raise PermissionError(f'Refuse to remove protected path: {path}')
    if path.is_file():
        path.unlink()
    elif path.is_dir():
        import shutil
        shutil.rmtree(path)


def _match_dir_name(name: str, patterns: set[str]) -> bool:
    """Return True if a directory name matches any glob-like pattern."""
    for pat in patterns:
        if pat.endswith('*'):
            if name.startswith(pat[:-1]):
                return True
        elif name == pat:
            return True
    return False


def _cleanup_temp_dirs(root: Path) -> list[Path]:
    """Recursively remove directories matching temp_dir_patterns under root."""
    removed = []
    patterns = CLEANUP_CONFIG['temp_dir_patterns']
    for item in root.rglob('*'):
        if item.is_dir() and _match_dir_name(item.name, patterns):
            _remove_path(item)
            removed.append(item)
    return removed


def _cleanup_old_backups(directory: Path, pattern: str, keep: int = 3) -> list[Path]:
    """Keep the most recent backup files matching pattern, remove the rest."""
    removed = []
    backups = sorted(directory.glob(pattern), key=lambda p: p.stat().st_mtime, reverse=True)
    for old in backups[keep:]:
        _remove_path(old)
        removed.append(old)
    return removed


def _cleanup_empty_root_dirs() -> list[Path]:
    """Remove empty directories directly under ROOT (excluding core folders)."""
    removed = []
    keep = CLEANUP_CONFIG['empty_root_keep']
    for item in ROOT.iterdir():
        if item.is_dir() and item.name not in keep:
            try:
                # list any content recursively
                contents = list(item.rglob('*'))
                if not contents:
                    _remove_path(item)
                    removed.append(item)
            except PermissionError:
                pass
    return removed


def cleanup_artifacts(dry_run: bool = False) -> dict[str, list[Path]]:
    """Clean up known by-products and intermediate files.

    Returns a mapping from category to list of paths that were (or would be) removed.
    """
    results: dict[str, list[Path]] = {}

    actions = [
        ('temp-dirs', _cleanup_temp_dirs, [ROOT]),
        ('empty-root-dirs', _cleanup_empty_root_dirs, []),
    ]
    for rule in CLEANUP_CONFIG['backup_rules']:
        actions.append((
            f"backups-{rule['directory'].name}",
            _cleanup_old_backups,
            [rule['directory'], rule['pattern'], rule['keep']],
        ))

    temp_patterns = CLEANUP_CONFIG['temp_dir_patterns']
    empty_keep = CLEANUP_CONFIG['empty_root_keep']

    for name, func, args in actions:
        if dry_run:
            # For dry-run, collect targets without deleting.
            targets: list[Path] = []
            if name == 'temp-dirs':
                targets = [
                    p for p in ROOT.rglob('*')
                    if p.is_dir() and _match_dir_name(p.name, temp_patterns)
                ]
            elif name == 'empty-root-dirs':
                targets = [
                    p for p in ROOT.iterdir()
                    if p.is_dir() and p.name not in empty_keep and not list(p.rglob('*'))
                ]
            elif name.startswith('backups-'):
                rule = next(
                    r for r in CLEANUP_CONFIG['backup_rules']
                    if f"backups-{r['directory'].name}" == name
                )
                targets = sorted(
                    rule['directory'].glob(rule['pattern']),
                    key=lambda p: p.stat().st_mtime,
                    reverse=True,
                )[rule['keep']:]
            results[name] = targets
        else:
            results[name] = func(*args)

    return results


def _render_template(template: str, context: dict[str, str]) -> str:
    """Replace {{ key }} placeholders in template with values from context."""
    html = template
    for key, value in context.items():
        placeholder = '{{ ' + key + ' }}'
        html = html.replace(placeholder, value)
    return html


def build() -> Path:
    """Run the full build process."""
    print('Loading workbench config...')
    config = load_workbench_config()
    tokens = get_active_tokens(config)
    print(f'  active theme: {config.get("activeTheme")}')

    print('Loading modules...')
    modules = load_modules(config)
    for m in modules:
        print(f'  loaded: {m.get("id")}')

    print('Enriching modules...')
    enriched_modules = {}
    for m in modules:
        mid = m.get('id')
        enriched = enrich_module(m)
        enriched = apply_tokens(enriched, tokens)
        enriched_modules[mid] = enriched

    print('Backing up workbench...')
    backup = backup_workbench()
    print(f'  backup: {backup}')

    print('Loading template...')
    if not TEMPLATE.exists():
        raise FileNotFoundError(f'Template not found: {TEMPLATE}')
    template = TEMPLATE.read_text(encoding='utf-8')

    print('Rendering reading module...')
    reading_constants = ''
    workspaces_array = ''
    if 'read' in enriched_modules:
        reading_constants, workspaces_array = _build_reading_workspace(enriched_modules['read'])
    else:
        print('  [skip] reading module not enabled or missing')

    print('Compiling styles...')
    styles_css = _compile_styles()

    print('Rendering workbench...')
    context = {
        'styles': styles_css,
        'theme_script': _build_theme_script(config),
        'reading_constants': reading_constants,
        'workspaces_array': workspaces_array,
    }
    html = _render_template(template, context)

    print('Writing workbench...')
    WORKBENCH.write_text(html, encoding='utf-8')

    print('Validating JS syntax...')
    validate_js(html)
    print('  JS syntax OK')

    return backup


def _report_cleaned(cleaned: dict[str, list[Path]], dry_run: bool) -> int:
    """Print cleanup results and return the number of artifacts."""
    label = 'would remove' if dry_run else 'removed'
    action = 'would be removed' if dry_run else 'removed'
    total = 0
    for category, paths in cleaned.items():
        if paths:
            print(f'  [{label}] {category}:')
            for p in paths:
                print(f'    [{datetime.now():%Y-%m-%d %H:%M:%S}] - {p.relative_to(ROOT)}')
            total += len(paths)
    if total == 0:
        print('  nothing to clean')
    else:
        print(f'  {total} artifact(s) {action}')
    return total


def _confirm_cleanup(cleaned: dict[str, list[Path]]) -> bool:
    """Print the cleanup list and ask the user for confirmation."""
    total = sum(len(paths) for paths in cleaned.values())
    if total == 0:
        print('Nothing to clean.')
        return True

    print(f'About to remove {total} artifact(s):')
    for category, paths in cleaned.items():
        if not paths:
            continue
        print(f'  [{category}]')
        for p in paths:
            print(f'    - {p.relative_to(ROOT)}')

    while True:
        try:
            answer = input('Proceed with cleanup? [y/N]: ').strip().lower()
        except EOFError:
            print('Non-interactive environment; use --dry-run to preview.')
            return False
        if answer in ('y', 'yes'):
            return True
        if answer in ('n', 'no', ''):
            print('Cleanup cancelled.')
            return False
        print('Please answer y or n.')


def main() -> int:
    parser = argparse.ArgumentParser(description='Build the 此刻便是春天 workbench.')
    parser.add_argument('--skip-validate', action='store_true', help='Skip running validate_workbench.py')
    parser.add_argument('--dry-run', action='store_true', help='Report artifacts to clean without building or deleting')
    parser.add_argument('--confirm', action='store_true', help='Confirm before removing artifacts')
    args = parser.parse_args()

    if args.dry_run:
        print('Dry-run: scanning for artifacts to clean (no build, no delete)...')
        _report_cleaned(cleanup_artifacts(dry_run=True), dry_run=True)
        return 0

    print('Pre-build cleanup...')
    pre_cleaned = cleanup_artifacts(dry_run=args.confirm)
    if args.confirm and not _confirm_cleanup(pre_cleaned):
        return 0
    if not args.confirm:
        _report_cleaned(pre_cleaned, dry_run=False)

    build()

    if not args.skip_validate:
        print('Running full validation...')
        run_validate()
        print('Validation passed.')

    print('Post-build cleanup...')
    post_cleaned = cleanup_artifacts(dry_run=args.confirm)
    if args.confirm and not _confirm_cleanup(post_cleaned):
        return 0
    if not args.confirm:
        _report_cleaned(post_cleaned, dry_run=False)

    if not args.skip_validate:
        print('Build and validation passed.')
    else:
        print('Build complete (validation skipped).')

    return 0


if __name__ == '__main__':
    sys.exit(main())
